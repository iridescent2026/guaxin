/**
 * 根据 promptKey 获取角色提示词
 */
export function getCharacterPrompt(key: string): CharacterPrompt | undefined {
  return CHARACTER_PROMPTS.find((c) => c.key === key);
}

/**
 * 获取所有角色列表（用于初始化数据库）
 */
export function getAllCharacters() {
  return CHARACTER_PROMPTS.map((c) => ({
    name: c.name,
    title: c.title,
    promptKey: c.key,
    personality: c.systemPrompt.slice(0, 200) + '...',
    tags: c.key === 'gentle_senior' ? ['温柔', '倾听', '共情']
      : c.key === 'rational_roommate' ? ['理性', '务实', '逻辑']
      : ['元气', '陪伴', '活力'],
  }));
}
